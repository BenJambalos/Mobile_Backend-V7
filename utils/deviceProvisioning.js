// Device PROVISIONING: how a physical HyQual device gets its PERMANENT
// Device ID and Device Key.
//
//   * OPTIONAL. Registering a device in the app does not need it: POST /api/devices
//     creates the record from the Device ID + Device Key the farmer types. This is
//     for generating credentials yourself, once per physical device, before it is
//     shipped or installed (scripts/provision_device.js). It never happens when a
//     farmer registers a device in the app.
//   * monitoring_devices is the central record: device_id is the permanent
//     Device ID, device_key is the permanent Device Key. A provisioned device
//     that nobody has registered yet has farm_id = NULL and pond_id = NULL (a
//     device a farmer removed looks the same).
//   * The two values are printed on the device's box / label and programmed
//     into the ESP32 firmware (DEVICE_ID / DEVICE_KEY). The farmer types the
//     same two values into the app to register the device (POST /api/devices,
//     see utils/deviceAssignment.js -> registerDevice).
//   * The key is never regenerated by registering, removing or moving a device.
const crypto = require('crypto');
const pool = require('../db');

// Same shape as every key issued so far ("dk_" + 32 hex characters), so the
// devices that already exist keep working and new ones look the same.
const DEVICE_KEY_PREFIX = 'dk_';

function generateDeviceKey() {
  return DEVICE_KEY_PREFIX + crypto.randomBytes(16).toString('hex');
}

// What a device is called until its farmer renames it.
function defaultDeviceName(deviceId) {
  return `Device ${deviceId}`;
}

// Compares the stored Device Key with the one a person typed. Both are hashed
// first so the comparison always takes the same time and never reveals how many
// leading characters were right. A device without a stored key never matches.
function keysMatch(storedKey, submittedKey) {
  if (typeof storedKey !== 'string' || !storedKey) return false;
  if (typeof submittedKey !== 'string' || !submittedKey) return false;
  const a = crypto.createHash('sha256').update(storedKey).digest();
  const b = crypto.createHash('sha256').update(submittedKey).digest();
  return crypto.timingSafeEqual(a, b);
}

// Creates ONE provisioned device: a monitoring_devices row with a fresh
// permanent key, no farm and no pond, plus its single (offline) status row.
// Returns { device_id, device_name, device_key }.
async function provisionOne(db) {
  for (let attempt = 0; attempt < 5; attempt++) {
    const key = generateDeviceKey();
    const conn = await db.getConnection();
    try {
      await conn.beginTransaction();
      const [ins] = await conn.query(
        `INSERT INTO monitoring_devices (farm_id, pond_id, device_name, status, device_key)
         VALUES (NULL, NULL, 'Device', 'active', ?)`,
        [key]
      );
      const id = ins.insertId;
      const name = defaultDeviceName(id);
      await conn.query('UPDATE monitoring_devices SET device_name = ? WHERE device_id = ?', [name, id]);
      // One current-status row per device, OFFLINE until the device first talks to the API.
      await conn.query(
        `INSERT INTO device_status (device_id, connectivity_status, active_sensors_count, recorded_at, last_seen_at)
         VALUES (?, 'offline', 0, NOW(), NULL)`,
        [id]
      );
      await conn.commit();
      return { device_id: id, device_name: name, device_key: key };
    } catch (err) {
      try { await conn.rollback(); } catch (_) { /* connection already gone */ }
      if (err.code === 'ER_DUP_ENTRY') continue; // a key clash is practically impossible; just draw another key
      throw err;
    } finally {
      conn.release();
    }
  }
  throw new Error('Could not generate a unique device key. Try again.');
}

// Provisions `count` new devices (1 to 500). Returns an array of
// { device_id, device_name, device_key } - the values to print on the box and
// to put in the firmware.
async function provisionDevices(count = 1, db = pool) {
  const n = Number(count);
  if (!Number.isInteger(n) || n < 1 || n > 500) {
    throw new Error('count must be a whole number from 1 to 500');
  }
  const created = [];
  for (let i = 0; i < n; i++) created.push(await provisionOne(db));
  return created;
}

module.exports = { DEVICE_KEY_PREFIX, generateDeviceKey, defaultDeviceName, keysMatch, provisionDevices };
